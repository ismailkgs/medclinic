CREATE TABLE patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name VARCHAR(100) NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    patronymic VARCHAR(100),
    phone VARCHAR(32) NOT NULL,
    keycloak_subject VARCHAR(255) UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE doctor_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_slots_doctor FOREIGN KEY (doctor_id) REFERENCES doctors(id) ON DELETE RESTRICT,
    CONSTRAINT chk_slots_time CHECK (ends_at > starts_at)
);

CREATE INDEX idx_slots_doctor_time ON doctor_slots (doctor_id, starts_at);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    slot_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'CREATED',
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_appointments_patient FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_slot FOREIGN KEY (slot_id) REFERENCES doctor_slots(id) ON DELETE RESTRICT,
    CONSTRAINT chk_appointments_status CHECK (status IN ('CREATED', 'COMPLETED', 'CANCELED')),
    CONSTRAINT chk_appointments_time CHECK (ends_at > starts_at)
);

CREATE UNIQUE INDEX uq_appointments_occupied_slot ON appointments (slot_id)
WHERE status IN ('CREATED', 'COMPLETED');

CREATE INDEX idx_appointments_patient_status ON appointments (patient_id, status, starts_at);

CREATE INDEX idx_appointments_slot ON appointments (slot_id);
