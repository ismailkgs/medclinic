ALTER TABLE lab_requests ADD COLUMN dispatched_at TIMESTAMPTZ;
CREATE TABLE doctor_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL REFERENCES doctors(id) ON DELETE RESTRICT,
    report_year INTEGER NOT NULL CHECK(report_year>=1970),
    total_count BIGINT NOT NULL DEFAULT 0,
    created_count BIGINT NOT NULL DEFAULT 0,
    completed_count BIGINT NOT NULL DEFAULT 0,
    canceled_count BIGINT NOT NULL DEFAULT 0,
    generated_at TIMESTAMPTZ,
    UNIQUE(doctor_id,report_year)
);
CREATE TABLE sms_notifications (
    id UUID PRIMARY KEY,
    appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointments(id) ON DELETE RESTRICT,
    phone VARCHAR(32) NOT NULL,
    message TEXT NOT NULL,
    state VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK(state IN ('PENDING','SENT','SIMULATED','SKIPPED','FAILED')),
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    provider_id VARCHAR(255),
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at TIMESTAMPTZ
);
CREATE INDEX idx_sms_pending ON sms_notifications(next_attempt_at) WHERE state='PENDING';
CREATE INDEX idx_appointments_reminders ON appointments(starts_at) WHERE status='CREATED';
