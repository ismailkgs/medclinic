CREATE TABLE lab_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL REFERENCES doctors(id) ON DELETE RESTRICT,
    patient_id BIGINT NOT NULL REFERENCES patients(id) ON DELETE RESTRICT,
    test_code VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'REQUESTED',
    scheduled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_lab_status CHECK (status IN ('REQUESTED', 'BOOKED', 'CANCELED')),
    CONSTRAINT chk_lab_booking_time CHECK (status <> 'BOOKED' OR scheduled_at IS NOT NULL)
);

CREATE INDEX idx_lab_patient_status ON lab_requests (patient_id, status);
CREATE INDEX idx_lab_doctor ON lab_requests (doctor_id);

CREATE TABLE outbox_events (
    id UUID PRIMARY KEY,
    topic VARCHAR(128) NOT NULL,
    event_key VARCHAR(64) NOT NULL,
    payload TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMPTZ
);

CREATE INDEX idx_outbox_pending ON outbox_events (created_at, id) WHERE published_at IS NULL;

CREATE TABLE processed_events (
    event_id UUID NOT NULL,
    handler VARCHAR(100) NOT NULL,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (event_id, handler)
);
